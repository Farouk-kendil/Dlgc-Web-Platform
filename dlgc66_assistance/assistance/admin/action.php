<?php

// =====================================================
// DLGC Assistance
// Actions sur les demandes d'assistance
// =====================================================

require __DIR__ . '/../lib/bootstrap.php';


// -----------------------------------------------------
// يجب أن يكون الموظف مسجل الدخول
// -----------------------------------------------------

require_admin();


// -----------------------------------------------------
// هذا الملف يقبل POST فقط
// -----------------------------------------------------

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    redirect('index.php');
}


// -----------------------------------------------------
// حماية CSRF
// -----------------------------------------------------

verify_csrf();


// -----------------------------------------------------
// قراءة البيانات
// -----------------------------------------------------

$id = filter_input(
    INPUT_POST,
    'id',
    FILTER_VALIDATE_INT
);

$action = trim(
    (string) ($_POST['action'] ?? '')
);


// -----------------------------------------------------
// التحقق من ID الطلب
// -----------------------------------------------------

if (!$id) {
    http_response_code(400);
    exit('Identifiant invalide.');
}


// -----------------------------------------------------
// الاتصال بقاعدة البيانات
// -----------------------------------------------------

$pdo = db();


// =====================================================
// 1. Prendre en charge
// =====================================================

if ($action === 'start') {

    /*
     * لا يتم أخذ الطلب إلا إذا كان ما زال Nouveau.
     *
     * هذا الشرط مهم جدًا لأن موظفين قد يكونان
     * فاتحين نفس الطلب في نفس الوقت.
     *
     * أول موظف يضغط Prendre en charge ينجح.
     * الثاني لن يستطيع تغيير صاحب الطلب.
     */

    $stmt = $pdo->prepare(
        "UPDATE assistance_requests
         SET
             status = 'en_cours',
             started_at = NOW(),
             assigned_admin_id = :admin_id
         WHERE id = :id
         AND status = 'nouveau'"
    );


    $stmt->execute([
        ':admin_id' => current_admin_id(),
        ':id' => $id,
    ]);


    /*
     * إذا لم يتم تحديث أي سطر فهذا يعني غالبًا:
     *
     * - موظف آخر أخذ الطلب قبله
     * - أو أن حالة الطلب تغيرت
     *
     * نعيده إلى صفحة الطلب حتى يرى الحالة الحالية
     * واسم الموظف الذي أخذه.
     */

    if ($stmt->rowCount() === 0) {
        redirect('ticket.php?id=' . $id);
    }


    // تم أخذ الطلب بنجاح
    redirect('ticket.php?id=' . $id);
}


// =====================================================
// 2. Marquer comme résolu
// =====================================================

if ($action === 'resolve') {

    /*
     * لا يتم حل الطلب إلا إذا كان En cours.
     *
     * الموظف الذي يضغط على زر Résolu
     * يتم تسجيله في resolved_by_admin_id.
     */

    $stmt = $pdo->prepare(
        "UPDATE assistance_requests
         SET
             status = 'resolu',
             resolved_at = NOW(),
             resolved_by_admin_id = :admin_id
         WHERE id = :id
         AND status = 'en_cours'"
    );


    $stmt->execute([
        ':admin_id' => current_admin_id(),
        ':id' => $id,
    ]);


    /*
     * إذا لم يتم تحديث أي سطر:
     *
     * قد يكون الطلب قد تم حله مسبقًا
     * أو تغيرت حالته.
     */

    if ($stmt->rowCount() === 0) {
        redirect('ticket.php?id=' . $id);
    }


    // تم حل الطلب بنجاح
    // وننتقل إلى Historique
    redirect('history.php');
}


// =====================================================
// Action inconnue
// =====================================================

http_response_code(400);

exit('Action inconnue.');